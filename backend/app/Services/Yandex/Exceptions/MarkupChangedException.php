<?php

namespace App\Services\Yandex\Exceptions;

/**
 * Страница открылась, но нужных данных в ней нет.
 *
 * Самая вероятная причина — Яндекс поменял вёрстку или структуру SSR-состояния,
 * и парсер нужно обновлять. Выносим это в отдельный тип, чтобы такую ошибку
 * было видно в логах отдельно от сетевых проблем.
 */
class MarkupChangedException extends YandexScraperException
{
    public static function missing(string $what): self
    {
        return new self("Не удалось найти {$what} на странице организации — похоже, Яндекс изменил разметку.");
    }

    /**
     * API вернул записи, но ни одна не разобралась в отзыв.
     *
     * Признак того, что поля переименовали. Без этой проверки парсер тихо
     * сохранил бы ноль отзывов и отчитался об успехе.
     */
    public static function unrecognisedReviews(): self
    {
        return new self('Яндекс вернул отзывы в неизвестном формате — похоже, изменилась структура ответа API.');
    }

    /**
     * Карточка обещает отзывы, а выгрузить не удалось ни одного.
     *
     * Расхождение между двумя независимыми источниками — сигнал, что сломался
     * обход, даже если каждый шаг по отдельности отработал без ошибок.
     */
    public static function noReviewsDespiteCounter(int $expected): self
    {
        return new self(
            "Карточка сообщает о {$expected} отзывах, но выгрузить не удалось ни одного — похоже, Яндекс изменил внутренний API."
        );
    }

    public function errorCode(): string
    {
        return 'markup_changed';
    }
}
